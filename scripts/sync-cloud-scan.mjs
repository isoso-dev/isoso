#!/usr/bin/env node
/**
 * Sync canonical line-scan from @isoso/core to Isoso Web (Deno edge functions).
 * Run from Isoso CLI root: npm run build && npm run sync:cloud
 */
import { copyFileSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const coreLineScan = resolve(root, "packages/isoso-core/src/line-scan.ts");
const webShared = resolve(root, "../Isoso Web/supabase/functions/_shared");
const webCore = resolve(webShared, "line-scan-core.ts");
const webEntry = resolve(webShared, "isoso-scan.ts");

copyFileSync(coreLineScan, webCore);

writeFileSync(
  webEntry,
  `/** Cloud scan entry — generated by Isoso CLI \`npm run sync:cloud\`. Do not edit manually. */
import {
  healthScore as coreHealthScore,
  scanSourceFile as coreScanSourceFile,
  type LineScanFinding,
} from "./line-scan-core.ts";

export type CloudFinding = LineScanFinding;

export function scanSourceFile(filePath: string, source: string): CloudFinding[] {
  return coreScanSourceFile(filePath, source);
}

export function healthScore(
  critical: number,
  serious: number,
  moderate: number,
  minor: number,
): number {
  return coreHealthScore(critical, serious, moderate, minor);
}
`,
  "utf8",
);

console.log("Synced line-scan to Isoso Web:", webCore);

const { jsxRules } = require(resolve(root, "packages/isoso-core/dist/rules/jsx-rules.js"));
const ruleIds = jsxRules.map((r) => r.id);
const applyFixesPath = resolve(webShared, "applyFixes.ts");
let applyFixes = readFileSync(applyFixesPath, "utf8");
const listBlock = `export const AUTO_FIX_RULE_IDS = [\n${ruleIds.map((id) => `  "${id}",`).join("\n")}\n] as const;`;
applyFixes = applyFixes.replace(
  /export const AUTO_FIX_RULE_IDS = \[[\s\S]*?\] as const;/,
  listBlock,
);
writeFileSync(applyFixesPath, applyFixes, "utf8");
console.log("Updated AUTO_FIX_RULE_IDS (%d rules) in applyFixes.ts", ruleIds.length);
